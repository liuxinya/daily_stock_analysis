def alias_for(name: str) -> Optional[str]:
    """营业部全名 → 游资昵称；没把握的返回 None（页面就显示营业部短名）。"""
    hit = alias_entry(name)
    return hit["alias"] if hit else None


def alias_entry(name: str) -> Optional[dict]:
    """营业部全名 → ``{"alias": 昵称, "source": 依据}``；没有把握返回 None。"""
    text = str(name or "")
    for keyword, alias, source in SEAT_ALIASES:
        if keyword and keyword in text:
            return {"alias": alias, "source": source}
    return None


